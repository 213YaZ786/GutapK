    // What it cannot read is said, never guessed.
    @Test
    fun unknownWordsStayWords() {
        assertTrue(Arm64.decode(0xd53b4200.toInt(), 0).startsWith(".inst"))
        assertEquals("udf\t#0", Arm64.decode(0, 0))
        assertEquals("nop", Arm64.decode(byteArrayOf(0x1f, 0x20, 0x03, 0xd5.toByte()), 0, 0))
    }
